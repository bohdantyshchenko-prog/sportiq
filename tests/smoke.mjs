import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const index=read('index.html'),sw=read('sw.js'),bootstrap=read('bootstrap-v5.js'),app=read('app-v5.js'),services=read('services.js'),styles=read('styles-v5.css'),config=read('config.js');
const manifest=JSON.parse(read('manifest.webmanifest'));
const scripts=[...index.matchAll(/<script src="([^"]+)"/g)].map(m=>m[1]);
const styleFiles=[...index.matchAll(/<link[^>]+href="([^"]+\.css)"/g)].map(m=>m[1]);
assert.ok(index.includes('NOVIQ 5.1'),'index must identify NOVIQ 5.1');
assert.deepEqual(scripts,['runtime-config.js','config.js','bootstrap-v5.js','data.js','services.js','app-v5.js']);
assert.deepEqual(styleFiles,['styles-v5.css']);
assert.ok(manifest.name.includes('5.1'));
for(const asset of[...scripts,...styleFiles,'manifest.webmanifest','icon.svg'])assert.ok(fs.existsSync(asset),`missing ${asset}`);
for(const script of scripts){new vm.Script(read(script),{filename:script});assert.ok(sw.includes(`'./${script}'`),`${script} missing from cache`)}
assert.ok(bootstrap.includes("version='5.1.0'")&&bootstrap.includes('noviq-v5-state'),'5.1 version or migration missing');
assert.ok(config.includes("storageKey: 'noviq-v5.1-state'"),'5.1 storage key missing');
assert.ok(app.includes('MATCH THESIS')&&app.includes('DECISION REPLAY')&&app.includes('AI BRIEFING'),'core loop missing');
assert.ok(app.includes('N.storage.export')&&app.includes('N.storage.import'),'data controls missing');
assert.ok(app.includes('N.health')&&services.includes('INVALID_NOVIQ_BACKUP'),'health or validated backups missing');
assert.ok(app.includes("language:'ru'")&&app.includes("language:'ua'")&&app.includes("language:'en'")||app.includes('const copy='),'localization dictionary missing');
assert.ok(app.includes('role="dialog"')&&app.includes('aria-modal="true"')&&app.includes('trapFocus'),'accessible dialogs missing');
assert.ok(app.includes('role="status"')&&app.includes('aria-live="polite"'),'accessible toast/status missing');
assert.ok(app.includes("data-testid=\"save-thesis\"")&&app.includes("data-testid=\"replay\""),'e2e hooks missing');
assert.ok(!app.includes('alert('),'native alerts are forbidden');
assert.ok(!index.includes('styles-world.css')&&!index.includes('ui-part-1.js'),'legacy UI must not load');
assert.ok(styles.includes('prefers-reduced-motion')&&styles.includes(':focus-visible'),'motion and keyboard accessibility missing');
assert.ok(sw.includes("request.mode==='navigate'"),'navigation fallback missing');
console.log(`NOVIQ 5.1 checks passed: ${scripts.length} scripts, ${styleFiles.length} stylesheet.`);